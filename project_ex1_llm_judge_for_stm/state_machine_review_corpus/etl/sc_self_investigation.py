"""Self-investigation of W2 SC median-aggregation pipeline.

Goal — explain why the SC final report (HAI=79.88) is much lower than each
individual rerun (HAI=83.55-83.66). Confirms a CRITICAL design flaw in the W2
confidence formula vs benchmark.py's downstream confidence-thresholded
heuristics.

Output:
- Side-by-side metric matrix: W1.5 / rerun0 / rerun1 / rerun2 / SC final
- Per-task agent_score variance across 3 reruns (62-task slice)
- Mechanistic explanation of EvidenceDiscipline / PDS / Calib drops

Run: python -m project_ex1_llm_judge_for_stm.state_machine_review_corpus.etl.sc_self_investigation
Data sources (gitignored, must be regenerated by rerunning W2 SC + W1.5):
- etl/out/phase14_combined/week2/checkpoints/week2_q3_q3_both_n3_62task_rerun{0,1,2}.json
- etl/out/phase14_combined/week2/report_q3_both_n3_62task.json
- etl/out/phase14_combined/week15/report_iter_b_only_62task.json

Output: etl/sc_self_investigation_data.json (committed), etl/sc_self_investigation_report.md (committed).
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

CORPUS_ROOT = Path(__file__).resolve().parent.parent
PHASE14 = CORPUS_ROOT / "etl" / "out" / "phase14_combined"
WK2 = PHASE14 / "week2"
WK15 = PHASE14 / "week15"
CKPT = WK2 / "checkpoints"
DATA_OUT = CORPUS_ROOT / "etl" / "sc_self_investigation_data.json"


def _resolve(d: dict, dotted: str):
    cur = d
    for p in dotted.split("."):
        if not isinstance(cur, dict) or p not in cur:
            return None
        cur = cur[p]
    return cur


def main() -> None:
    if not (CKPT.exists() and (WK15 / "report_iter_b_only_62task.json").exists()):
        raise SystemExit(
            "Required artefacts missing under etl/out/. Re-run Week 2 SC "
            "(run_self_consistency_config.py) and Week 1.5 iter_b_only_62task first."
        )

    reruns = [
        json.loads((CKPT / f"week2_q3_q3_both_n3_62task_rerun{i}.json").read_text())
        for i in range(3)
    ]
    final = json.loads((WK2 / "report_q3_both_n3_62task.json").read_text())
    wk15 = json.loads((WK15 / "report_iter_b_only_62task.json").read_text())

    # 1. side-by-side metric matrix
    metric_specs = [
        ("HAI", "HAI"),
        ("HAI_legacy", "HAI_legacy"),
        ("RAS", "record_metrics.RAS"),
        ("SAS", "summary_metrics.SAS"),
        ("CRAS", "component_metrics.CRAS"),
        ("PDS", "protocol_metrics.PDS"),
        ("record_ScoreAlign", "record_metrics.ScoreAlign"),
        ("record_Calib", "record_metrics.Calib"),
        ("record_ReasonAlign", "record_metrics.ReasonAlign"),
        ("record_EquivAlign", "record_metrics.EquivAlign"),
        ("issue_f1", "record_metrics.issue_f1"),
        ("summary_ScoreAlign", "summary_metrics.ScoreAlign"),
        ("summary_RankAlign", "summary_metrics.RankAlign"),
        ("summary_Spearman", "summary_metrics.spearman_rho"),
        ("summary_EvidenceDisc", "summary_metrics.EvidenceDiscipline"),
        ("summary_Stability", "summary_metrics.Stability"),
        ("weighted_kappa", "judgement_metrics.weighted_kappa"),
    ]
    matrix = {}
    for label, path in metric_specs:
        matrix[label] = {
            "W1.5_baseline": _resolve(wk15, path),
            "rerun_0_T0_V1": _resolve(reruns[0], path),
            "rerun_1_T03_V2": _resolve(reruns[1], path),
            "rerun_2_T05_V3": _resolve(reruns[2], path),
            "SC_median_aggregated": _resolve(final, path),
        }

    # 2. per-task variance across 3 reruns (62 tasks)
    def by_id(rep): return {row["task_id"]: row for row in rep["normalized_rows"]}
    rerun_idx = [by_id(r) for r in reruns]
    score_stds, score_ranges, max_dim_stds, judge_disagreements = [], [], [], []
    for tid in rerun_idx[0]:
        rows = [rerun_idx[k].get(tid) for k in range(3)]
        if any(r is None for r in rows):
            continue
        scores = [r.get("agent_score") for r in rows if r.get("agent_score") is not None]
        if len(scores) == 3:
            score_stds.append(statistics.pstdev(scores))
            score_ranges.append(max(scores) - min(scores))
        dims = [r.get("agent_dim_scores", {}) for r in rows]
        common = set(dims[0]) & set(dims[1]) & set(dims[2])
        if common:
            max_dim_stds.append(max(statistics.pstdev([dims[k][d] for k in range(3)]) for d in common))
        judges = {r.get("agent_judgement") for r in rows}
        if len(judges) > 1:
            judge_disagreements.append(tid)

    rerun_consistency = {
        "n_tasks": len(rerun_idx[0]),
        "agent_score_identical_count": sum(1 for s in score_stds if s < 0.001),
        "agent_score_median_std": statistics.median(score_stds) if score_stds else None,
        "agent_score_mean_std": statistics.mean(score_stds) if score_stds else None,
        "agent_score_max_std": max(score_stds) if score_stds else None,
        "max_dim_std_median": statistics.median(max_dim_stds) if max_dim_stds else None,
        "max_dim_std_mean": statistics.mean(max_dim_stds) if max_dim_stds else None,
        "max_dim_std_max": max(max_dim_stds) if max_dim_stds else None,
        "judgement_disagreement_task_count": len(judge_disagreements),
        "judgement_disagreement_task_ids": judge_disagreements,
    }

    # 3. confidence formula bug evidence
    confidence_bug = {
        "rerun_0_summary_avg_confidence": statistics.mean(
            r["agent_confidence"] for r in reruns[0]["normalized_rows"]
            if r.get("eval_bucket") == "summary" and r.get("agent_confidence") is not None
        ),
        "SC_final_summary_avg_confidence": statistics.mean(
            r["agent_confidence"] for r in final["normalized_rows"]
            if r.get("eval_bucket") == "summary" and r.get("agent_confidence") is not None
        ),
        "summary_self_awareness_threshold": 0.70,
        "protocol_confidence_discipline_threshold": 0.55,
        "summary_self_awareness_pass_rate_rerun_0": sum(
            1 for r in reruns[0]["normalized_rows"]
            if r.get("eval_bucket") == "summary"
            and (r.get("agent_confidence") or 1.0) <= 0.70
            and (r.get("evidence_discipline_score") or 0.0) >= 0.60
        ) / max(1, sum(1 for r in reruns[0]["normalized_rows"] if r.get("eval_bucket") == "summary")),
        "summary_self_awareness_pass_rate_SC_final": sum(
            1 for r in final["normalized_rows"]
            if r.get("eval_bucket") == "summary"
            and (r.get("agent_confidence") or 1.0) <= 0.70
            and (r.get("evidence_discipline_score") or 0.0) >= 0.60
        ) / max(1, sum(1 for r in final["normalized_rows"] if r.get("eval_bucket") == "summary")),
    }

    # 4. structural divergence: rerun_0 (T=0+V1, nominally same as W1.5) vs W1.5
    wk_idx = by_id(wk15)
    score_diff_count = 0
    judgement_diff_count = 0
    common_tasks = set(rerun_idx[0]) & set(wk_idx)
    for tid in common_tasks:
        a, b = rerun_idx[0][tid], wk_idx[tid]
        if abs((a.get("agent_score") or 0) - (b.get("agent_score") or 0)) > 0.01:
            score_diff_count += 1
        if a.get("agent_judgement") != b.get("agent_judgement"):
            judgement_diff_count += 1
    pipeline_divergence = {
        "common_tasks": len(common_tasks),
        "agent_score_differs_count": score_diff_count,
        "agent_judgement_differs_count": judgement_diff_count,
        "note": "W1.5 baseline does not save agent_dim_scores into normalized_rows, so dim-level comparison is unavailable. The agent_score divergence may stem from API non-determinism (separate concern, deferred per user request) OR SC-pipeline post-LLM scoring divergence.",
    }

    out = {
        "context": {
            "slice": "62-task (18 record + 16 summary + 24 component + 4 protocol)",
            "config": "rubric=on, iter_b=on, variance_source=both, n_reruns=3",
            "rerun_overrides": {
                "rerun_0": {"temperature_override": 0.0, "rubric_prompt_variant": "v1"},
                "rerun_1": {"temperature_override": 0.3, "rubric_prompt_variant": "v2"},
                "rerun_2": {"temperature_override": 0.5, "rubric_prompt_variant": "v3"},
            },
        },
        "metric_matrix": matrix,
        "rerun_consistency": rerun_consistency,
        "confidence_formula_bug_evidence": confidence_bug,
        "sc_pipeline_vs_standard_pipeline_divergence": pipeline_divergence,
    }
    DATA_OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2, default=str))
    print(f"Self-investigation data written: {DATA_OUT}")
    print(f"  metric_matrix: {len(matrix)} metrics")
    print(f"  rerun_consistency.agent_score_identical_count: "
          f"{rerun_consistency['agent_score_identical_count']}/{rerun_consistency['n_tasks']}")
    print(f"  confidence: rerun_0 avg = {confidence_bug['rerun_0_summary_avg_confidence']:.3f}, "
          f"SC final avg = {confidence_bug['SC_final_summary_avg_confidence']:.3f}")
    print(f"  self_awareness_pass_rate: rerun_0 = "
          f"{confidence_bug['summary_self_awareness_pass_rate_rerun_0']:.2%}, "
          f"SC final = {confidence_bug['summary_self_awareness_pass_rate_SC_final']:.2%}")


if __name__ == "__main__":
    main()
